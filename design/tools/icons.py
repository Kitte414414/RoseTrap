import re, json
F = '/tmp/fluent/package/icons/'
def fluent(n):
    svg = open(F + n + '_24_filled.svg').read()
    return ''.join(re.findall(r'<path[^>]* d="([^"]+)"', svg))
fa = open('/tmp/fa/package/svgs/solid/screwdriver-wrench.svg').read()
fa_d = re.search(r'<path[^>]* d="([^"]+)"', fa).group(1)
fa_vb = [float(v) for v in re.search(r'viewBox="([^"]+)"', fa).group(1).split()]

raw = {
    'General': fluent('data_pie'), 'Globe': fluent('globe'), 'Cursor': fluent('cursor'),
    'FFlags': fluent('flag'), 'Gear': fluent('settings'), 'Square': fluent('square'),
    'Preset': fluent('layer'), 'Shaders': fluent('image'), 'Appearance': fluent('image_multiple'),
    'Potato': fluent('top_speed'), 'Balanced': fluent('scales'), 'Quality': fluent('diamond'), 'Custom': fluent('options'),
    'Play': fluent('play'), 'Close': fluent('dismiss'), 'Folder': fluent('folder_open'),
    'Tools': fa_d,
    'Shooter': fluent('target'), 'Fight': fluent('flash'), 'World': fluent('map'),
    'Simulator': fluent('leaf_three'), 'Atmosphere': fluent('weather_moon'), 'Sparkle': fluent('sparkle'),
}
lines = ['// <auto-generated> by design/tools/icons.py from Fluent UI System Icons (MIT) and Font Awesome Free (CC BY 4.0).',
         'namespace RoseTrap.Theme;', '', 'internal static class IconData', '{']
for k, v in raw.items():
    lines.append(f'    public const string {k} = "{v}";')
lines.append(f'    public const double ToolsWidth = {fa_vb[2]:g}, ToolsHeight = {fa_vb[3]:g};')
lines.append('}')
open('/tmp/hoplite/workspace/src/RoseTrap/Theme/IconData.g.cs', 'w').write('\n'.join(lines) + '\n')
print('ok', len(raw))
