"""Generates src/RoseTrap/Controls/LogoRoseData.g.cs from design/rosetrap-ascii-rose.svg."""
import re
root = '/tmp/hoplite/workspace/'
svg = open(root + 'design/rosetrap-ascii-rose.svg', encoding='utf-8').read()
vb = [float(v) for v in re.search(r'viewBox="([^"]+)"', svg).group(1).split()]
geo, col = [], []
for m in re.finditer(r'<rect ([^>]*)/>', svg):
    a = dict(re.findall(r'(\w+)="([^"]*)"', m.group(1)))
    x, y, w, h = (float(a[k]) for k in ('x', 'y', 'width', 'height'))
    rx = min(float(a.get('rx', 0)), w / 2, h / 2)
    alpha = round(float(a.get('opacity', 1)) * 255)
    geo.append(f'{x - vb[0]:g}f, {y - vb[1]:g}f, {w:g}f, {h:g}f, {rx:g}f')
    col.append(f'0x{(alpha << 24) | int(a["fill"].lstrip("#"), 16):08X}')

def wrap(items, per):
    return '\n'.join('        ' + ', '.join(items[i:i + per]) + ',' for i in range(0, len(items), per))

out = f'''// <auto-generated> by design/tools/logo_rose.py from design/rosetrap-ascii-rose.svg. Do not edit.
namespace RoseTrap.Controls;

internal static class LogoRoseData
{{
    public const float Size = {vb[2]:g}f;

    /// <summary>x, y, width, height, corner radius per dash (view-box units).</summary>
    public static readonly float[] Dashes =
    [
{wrap(geo, 2)}
    ];

    /// <summary>ARGB colour per dash.</summary>
    public static readonly uint[] Colors =
    [
{wrap(col, 8)}
    ];
}}
'''
open(root + 'src/RoseTrap/Controls/LogoRoseData.g.cs', 'w', encoding='utf-8').write(out)
print(len(geo), 'dashes')
